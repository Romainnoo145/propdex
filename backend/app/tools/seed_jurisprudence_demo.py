"""Seed a curated, verified set of omgevingsrecht jurisprudence for the demo.

WHY THIS EXISTS
---------------
The jurisprudence tab reads `RulingCache` (a pure DB read via
`GET /api/jurisprudence/explorer`). For the demo relaunch the AI ingestion /
analysis worker is switched off, so no new rows are produced and the previously
AI-generated rows in `RulingCache` were unreliable (wrong uitkomst /
doorlooptijd / rechtsgronden). This tool replaces them with a hand-curated +
source-verified set so the explorer shows a rich, accurate, production-like
dataset.

DATA SET (`seed_jurisprudence_demo_data.json`)
----------------------------------------------
Every record is a REAL, existing ruling (verifiable on data.rechtspraak.nl).
The set spans ~440 rulings:
  - ~74 Rechtbank Limburg rulings where gemeente Venlo is the verweerder (the
    demo hero set), of which 12 are additionally hand-verified against the
    source uitspraak (incl. nuanced partial outcomes), and
  - ~370 further Rechtbank Limburg + Raad van State (nationwide) omgevingsrecht
    rulings as supporting cast for the global explorer — ~70 distinct gemeenten
    in total.

The full Venlo set was harvested by scanning the broader `bestuursrecht`
subject feed (the narrow `bestuursrecht_omgevingsrecht` tag is applied to only
~5% of relevant rulings — this is the same root cause fixed in production
ingestion, see app/government_apis/rechtspraak.py) and filtering to the
omgevingsrecht domain (dropping Opiumwet-woningsluiting, bijstand, WOZ, BRP,
Leerplicht and similar non-omgevingsrecht bestuursrecht).

For every record the `uitkomst` is derived from the operative dictum
(beslissing) of the source ruling — never an AI guess:
    ongegrond -> afgewezen | (beroep) gegrond -> toegewezen |
    gegrond + gedeeltelijk/voor-zover vernietigd -> gedeeltelijk.
`datum_uitspraak` comes from the ruling metadata, `doorlooptijd_dagen` from the
days between the contested first-instance besluit and the ruling (only set for
first-instance Rechtbank cases, where it is meaningful), `vergunningstype` /
`rechtsgronden` from conservative keyword classification of the ruling text, and
`tegenstanders` from named organisations (Stichting/Vereniging/...) in the
header. No ECLI, date or outcome is fabricated.

`full_text` is intentionally left empty — the (disabled) AI jobs are its only
consumer and the explorer never displays it.

The JSON is regenerated by the offline builder (see git history / the throwaway
fetch+extract scripts); this tool only upserts the committed snapshot, so the
seed itself makes no network calls and is fully deterministic.

SAFETY
------
This tool DELETES existing rows in the shared (org-agnostic) `RulingCache`
table (the Venlo rows + every ECLI in the seed) before inserting the curated
set. Because that touches shared production data it refuses to run unless
explicitly confirmed:

    PYTHONPATH=. python -m app.tools.seed_jurisprudence_demo --confirm
    # or
    SEED_CONFIRM=1 PYTHONPATH=. python -m app.tools.seed_jurisprudence_demo
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any, TypedDict, cast

from sqlalchemy import CursorResult, delete, or_
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker, create_async_engine

from app.core.config import settings
from app.government_apis.ecli_registry import GEMEENTE_TO_RECHTBANK
from app.models.ruling_cache import RulingCache

# The demo hero gemeente — its rows are always replaced wholesale.
GEMEENTE = "Venlo"

DATA_FILE = Path(__file__).with_name("seed_jurisprudence_demo_data.json")


class DemoRuling(TypedDict):
    ecli: str
    court_code: str
    instantie: str
    datum_uitspraak: str
    title: str
    summary: str
    uitkomst: str  # toegewezen | afgewezen | gedeeltelijk | onbekend
    vergunningstype: str
    rechtsgronden: list[str]
    tegenstanders: list[str]
    extracted_gemeente: str | None
    doorlooptijd_dagen: int | None


def load_rulings() -> list[DemoRuling]:
    """Load and lightly validate the committed, source-verified ruling set."""
    with DATA_FILE.open(encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, list) or not data:
        raise ValueError(f"{DATA_FILE.name} must contain a non-empty JSON list")
    return cast("list[DemoRuling]", data)


def _build_row(ruling: DemoRuling, now: datetime) -> dict[str, Any]:
    """Map a curated entry to a RulingCache row payload.

    `ai_analysis` mirrors the structure the (now-disabled) analysis job would
    have produced, so the explorer's aggregation reads exactly as before — only
    with verified instead of hallucinated values.
    """
    ai_analysis = {
        "ecli": ruling["ecli"],
        "bezwaargrond": ruling["summary"],
        "uitkomst": ruling["uitkomst"],
        "relevantie": ruling["summary"],
        "confidence": "HIGH",
        "vergunningstype": ruling["vergunningstype"],
        "rechtsgronden": ruling["rechtsgronden"],
        "tegenstanders": ruling["tegenstanders"],
    }
    return {
        "ecli": ruling["ecli"],
        "court_code": ruling["court_code"],
        "instantie": ruling["instantie"],
        "datum_uitspraak": ruling["datum_uitspraak"],
        "title": ruling["title"],
        "summary": ruling["summary"],
        "full_text": None,
        "gemeente_query": ruling["extracted_gemeente"],
        "extracted_gemeente": ruling["extracted_gemeente"],
        "uitkomst": ruling["uitkomst"],
        "fetched_at": now,
        "ai_analysis": ai_analysis,
        "vergunningstype": ruling["vergunningstype"],
        "datum_indiening": None,
        "doorlooptijd_dagen": ruling["doorlooptijd_dagen"],
        "ai_analyzed_at": now,
        "rechtsgronden": ruling["rechtsgronden"],
        "tegenstanders": ruling["tegenstanders"],
    }


async def seed_jurisprudence(db: AsyncSession, *, full_reset: bool = False) -> int:
    """Replace rows in RulingCache with the curated set.

    By default only the Venlo rows + the curated ECLIs are replaced; other
    gemeenten's rows are left untouched (conservative). With ``full_reset=True``
    the ENTIRE ruling_cache table is wiped first, so the explorer shows ONLY the
    curated, source-verified set everywhere — use this for the demo, where any
    remaining legacy AI-analysed rows (other gemeenten) are unreliable.

    full_reset is also what keeps a Railway restore reproducible: restoring the
    pre-teardown dump brings back the old hallucinated rows, and re-running this
    seed with --full-reset collapses them back to the curated set.

    Returns the number of curated rows written.
    """
    rulings = load_rulings()
    now = datetime.now(UTC).replace(tzinfo=None)
    seeded_eclis = [r["ecli"] for r in rulings]

    # 1. Delete the rows we are about to replace.
    if full_reset:
        # Wipe everything — the curated set becomes the single source of truth.
        delete_stmt = delete(RulingCache)
    else:
        # Conservative: every Venlo row (so stale Venlo rows not in the new set
        # are removed) plus any row whose ECLI is in the curated set.
        delete_stmt = delete(RulingCache).where(
            or_(
                RulingCache.gemeente_query == GEMEENTE,
                RulingCache.extracted_gemeente == GEMEENTE,
                RulingCache.ecli.in_(seeded_eclis),
            )
        )
    deleted = cast("CursorResult[Any]", await db.execute(delete_stmt))
    scope = "ALL" if full_reset else "Venlo + seeded"
    print(f"[seed] Deleted {deleted.rowcount} existing rows from ruling_cache ({scope})")

    # 2. Upsert the curated set (idempotent on the ECLI primary key).
    for ruling in rulings:
        row = _build_row(ruling, now)
        stmt = pg_insert(RulingCache).values(row)
        stmt = stmt.on_conflict_do_update(
            index_elements=["ecli"],
            set_={k: v for k, v in row.items() if k != "ecli"},
        )
        await db.execute(stmt)

    await db.commit()
    venlo = sum(1 for r in rulings if r["extracted_gemeente"] == GEMEENTE)
    print(
        f"[seed] Upserted {len(rulings)} curated rulings "
        f"({venlo} Venlo + {len(rulings) - venlo} overige Limburg/Raad van State)"
    )
    return len(rulings)


def _parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Seed curated demo jurisprudence.")
    parser.add_argument(
        "--confirm",
        action="store_true",
        help="Required to actually mutate ruling_cache (deletes + inserts rows).",
    )
    parser.add_argument(
        "--full-reset",
        action="store_true",
        help=(
            "Wipe the ENTIRE ruling_cache table before inserting, so only the "
            "curated set remains (drops legacy AI rows for other gemeenten). "
            "Recommended for the demo."
        ),
    )
    return parser.parse_args()


async def main() -> None:
    if GEMEENTE not in GEMEENTE_TO_RECHTBANK:
        print(
            f"[seed] ABORT: gemeente '{GEMEENTE}' is not in the ECLI registry; "
            "the explorer/filters would not surface these rows.",
            file=sys.stderr,
        )
        sys.exit(1)

    args = _parse_args()
    full_reset = args.full_reset or os.environ.get("SEED_FULL_RESET") == "1"
    confirmed = args.confirm or os.environ.get("SEED_CONFIRM") == "1"

    if not confirmed:
        scope = (
            "the ENTIRE ruling_cache table"
            if full_reset
            else "the Venlo rows + seeded ECLIs in the shared ruling_cache table"
        )
        print(
            "[seed] REFUSING to run without confirmation.\n"
            f"       This DELETES {scope}\n"
            "       and replaces them with the curated set.\n"
            "       Re-run with --confirm (or SEED_CONFIRM=1) once you are sure the\n"
            "       DATABASE_URL points at the intended (demo) database.",
            file=sys.stderr,
        )
        sys.exit(2)

    engine = create_async_engine(settings.DATABASE_URL)
    session_factory = async_sessionmaker(engine, expire_on_commit=False)
    try:
        async with session_factory() as db:
            await seed_jurisprudence(db, full_reset=full_reset)
    finally:
        await engine.dispose()


if __name__ == "__main__":
    import asyncio

    asyncio.run(main())
